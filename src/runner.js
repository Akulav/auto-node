/**
 * Process management for websites.
 *
 * On Linux with systemd (production) every website becomes a systemd service
 * (`autonode-site-<name>.service`) running as the unprivileged `autonode` user,
 * so sites survive reboots and crashes even if the dashboard is down.
 *
 * In dev mode (or on Linux without systemd) a simple in-process supervisor is
 * used instead.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import * as config from './config.js';
import * as rust from './rust.js';
import { run, runOk, which, LineBuffer, isLinux } from './util.js';

const nodeBinDir = path.dirname(process.execPath);
export const unitName = (name) => `autonode-site-${name}.service`;
const scriptPath = (name) => path.join(config.paths.runDir, `${name}.sh`);
const legacyScriptPath = (name) => path.join(config.paths.configDir, 'run', `${name}.sh`); // ≤ 1.0.0, unreadable by the site user
const envPath = (name) => path.join(config.paths.envDir, `${name}.env`);

function useSystemd() {
  return !config.DEV && isLinux && !!which('systemctl') && fs.existsSync('/run/systemd/system');
}

let siteIds = null;
/** uid/gid of the `autonode` user (null in dev). */
export async function siteUser() {
  if (config.DEV || !isLinux) return null;
  if (siteIds) return siteIds;
  const uid = Number((await run('id', ['-u', config.SITE_USER], { quiet: true })).stdout.trim());
  const gid = Number((await run('id', ['-g', config.SITE_USER], { quiet: true })).stdout.trim());
  if (Number.isInteger(uid) && uid > 0) siteIds = { uid, gid };
  return siteIds;
}

export function siteEnv(site) {
  // Rust sites also get the autonode user's ~/.cargo/bin (where rustup installs cargo).
  const extra = rust.kindOf(path.join(config.paths.sitesDir, site.name)) === 'rust' ? `${rust.cargoBinDir()}:` : '';
  return {
    PATH: `${nodeBinDir}:${extra}/usr/local/bin:/usr/bin:/bin`,
    HOME: config.paths.homeDir,
    NODE_ENV: 'production',
    PORT: String(site.port),
    HOST: '127.0.0.1',
    // Persistent folder for databases/uploads: updates, rollbacks and "clean" never touch it.
    DATA_DIR: path.join(config.paths.siteDataRoot, site.name),
    ...site.env,
  };
}

function envFileContent(env) {
  return (
    Object.entries(env)
      .map(([k, v]) => `${k}="${String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`)
      .join('\n') + '\n'
  );
}

/* ---------------------------------------------------------------- systemd */

/**
 * systemd's *TimestampMonotonic values are CLOCK_MONOTONIC microseconds — the
 * same clock as process.hrtime(). Don't compare them with os.uptime(): inside
 * LXC/Proxmox containers that reports the container's uptime, not the host's,
 * which made every site show "Up 0s".
 */
export const monotonicNowUs = () => Number(process.hrtime.bigint() / 1000n);
export function uptimeSeconds(sinceUs, nowUs = monotonicNowUs()) {
  if (!Number.isFinite(sinceUs) || sinceUs <= 0) return null;
  return Math.max(0, (nowUs - sinceUs) / 1e6);
}

/** Optional memory cap: systemd kills (and, with Restart=always, restarts) a site that goes over it. */
function memoryLine(site) {
  const mb = Number(site.memoryLimitMB);
  return Number.isInteger(mb) && mb >= 64 && mb <= 1048576 ? `MemoryMax=${mb}M\n` : '';
}

const systemd = {
  /** Write script, env file and unit. Returns true if the unit changed. */
  async write(site, command) {
    const dir = path.join(config.paths.sitesDir, site.name);
    fs.mkdirSync(config.paths.runDir, { recursive: true, mode: 0o755 });
    const script = scriptPath(site.name);
    fs.writeFileSync(script, `#!/bin/sh\n# Generated by AutoNode. Edit the site in the dashboard instead.\ncd "${dir}" || exit 1\nexec ${command}\n`, { mode: 0o755 });
    fs.chmodSync(script, 0o755); // writeFileSync's mode only applies to new files
    fs.rmSync(legacyScriptPath(site.name), { force: true });
    fs.writeFileSync(envPath(site.name), envFileContent(siteEnv(site)), { mode: 0o600 });
    const unit = `# Generated by AutoNode - https://github.com/Akulav
[Unit]
Description=AutoNode website: ${site.name}
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=${config.SITE_USER}
Group=${config.SITE_USER}
WorkingDirectory=${dir}
EnvironmentFile=${envPath(site.name)}
ExecStart=/bin/sh ${scriptPath(site.name)}
Restart=always
RestartSec=3
KillMode=mixed
TimeoutStopSec=15
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
LimitNOFILE=65536
${memoryLine(site)}
[Install]
WantedBy=multi-user.target
`;
    const file = path.join(config.paths.unitDir, unitName(site.name));
    let old = null;
    try {
      old = fs.readFileSync(file, 'utf8');
    } catch {}
    if (old !== unit) {
      fs.writeFileSync(file, unit);
      await runOk('systemctl', ['daemon-reload']);
      return true;
    }
    return false;
  },
  async start(site, command) {
    await this.write(site, command);
    await runOk('systemctl', ['enable', unitName(site.name)]);
    await runOk('systemctl', ['restart', unitName(site.name)]);
  },
  async stop(site) {
    await run('systemctl', ['disable', unitName(site.name)], { quiet: true });
    await runOk('systemctl', ['stop', unitName(site.name)]);
  },
  async remove(name) {
    await run('systemctl', ['disable', '--now', unitName(name)], { quiet: true });
    for (const f of [path.join(config.paths.unitDir, unitName(name)), scriptPath(name), legacyScriptPath(name), envPath(name)]) fs.rmSync(f, { force: true });
    await run('systemctl', ['daemon-reload'], { quiet: true });
  },
  prevCpu: new Map(),
  async statusAll(names) {
    const out = {};
    if (!names.length) return out;
    const props = 'ActiveState,SubState,MainPID,ActiveEnterTimestampMonotonic,MemoryCurrent,CPUUsageNSec,NRestarts,LoadState';
    const r = await run('systemctl', ['show', ...names.map(unitName), `--property=${props}`], { quiet: true });
    const blocks = r.stdout.trim().split(/\n\s*\n/);
    const nowUs = monotonicNowUs();
    names.forEach((name, i) => {
      const p = {};
      for (const line of (blocks[i] || '').split('\n')) {
        const j = line.indexOf('=');
        if (j > 0) p[line.slice(0, j)] = line.slice(j + 1);
      }
      let state = 'stopped';
      if (p.LoadState === 'not-found') state = 'stopped';
      else if (p.ActiveState === 'active') state = 'running';
      else if (p.ActiveState === 'activating' && p.SubState === 'auto-restart') state = 'crashed';
      else if (p.ActiveState === 'activating') state = 'starting';
      else if (p.ActiveState === 'failed') state = 'crashed';
      const mem = Number(p.MemoryCurrent);
      const cpuNs = Number(p.CPUUsageNSec);
      let cpu = null;
      const prev = this.prevCpu.get(name);
      const now = process.hrtime.bigint();
      if (Number.isFinite(cpuNs)) {
        if (prev && prev.cpuNs <= cpuNs) {
          const wall = Number(now - prev.at);
          cpu = wall > 0 ? ((cpuNs - prev.cpuNs) / wall / os.cpus().length) * 100 : null;
        }
        this.prevCpu.set(name, { cpuNs, at: now });
      }
      const since = Number(p.ActiveEnterTimestampMonotonic);
      out[name] = {
        state,
        pid: Number(p.MainPID) || null,
        memory: Number.isFinite(mem) && mem < 2 ** 60 ? mem : null,
        cpu,
        restarts: Number(p.NRestarts) || 0,
        uptime: state === 'running' ? uptimeSeconds(since, nowUs) : null,
      };
    });
    return out;
  },
  async logs(name, lines = 300) {
    const r = await run('journalctl', ['-u', unitName(name), '-n', String(lines), '--no-pager', '-o', 'short-iso'], { quiet: true });
    return r.stdout;
  },
  follow(name, onLine) {
    const child = spawn('journalctl', ['-u', unitName(name), '-f', '-n', '0', '--no-pager', '-o', 'short-iso']);
    const buf = new LineBuffer(10);
    buf.listeners.add(onLine);
    child.stdout.on('data', (d) => buf.push(String(d)));
    child.on('error', () => {});
    return () => child.kill();
  },
};

/* ------------------------------------------------------------ child (dev) */

const children = new Map(); // name -> { proc, logs, state, startedAt, restarts, wanted }

const child = {
  async start(site, command) {
    await this.stop(site);
    const entry = children.get(site.name) || { logs: new LineBuffer(2000), restarts: 0 };
    entry.wanted = true;
    children.set(site.name, entry);
    const launch = () => {
      const dir = path.join(config.paths.sitesDir, site.name);
      const env = { ...process.env, ...siteEnv(site), PATH: process.env.PATH };
      const proc = spawn(command, { cwd: dir, env, shell: true, windowsHide: true });
      entry.proc = proc;
      entry.state = 'running';
      entry.startedAt = Date.now();
      const stamp = () => new Date().toISOString().replace('T', ' ').slice(0, 19);
      entry.logs.add(`${stamp()} ▶ Starting: ${command}`);
      proc.stdout.on('data', (d) => entry.logs.push(String(d)));
      proc.stderr.on('data', (d) => entry.logs.push(String(d)));
      proc.on('error', (e) => entry.logs.add(`${stamp()} ✖ ${e.message}`));
      proc.on('exit', (code) => {
        entry.proc = null;
        entry.logs.add(`${stamp()} ■ Exited with code ${code}`);
        if (entry.wanted) {
          entry.state = 'crashed';
          entry.restarts++;
          entry.timer = setTimeout(() => entry.wanted && launch(), Math.min(30_000, 1000 * 2 ** Math.min(entry.restarts, 5)));
        } else entry.state = 'stopped';
      });
    };
    launch();
  },
  async stop(site) {
    const entry = children.get(site.name);
    if (!entry) return;
    entry.wanted = false;
    clearTimeout(entry.timer);
    if (entry.proc) {
      const p = entry.proc;
      await new Promise((resolve) => {
        p.once('exit', resolve);
        if (process.platform === 'win32') spawn('taskkill', ['/pid', String(p.pid), '/T', '/F'], { windowsHide: true });
        else p.kill('SIGTERM');
        setTimeout(resolve, 5000);
      });
    }
    entry.state = 'stopped';
  },
  async remove(name) {
    await this.stop({ name });
    children.delete(name);
  },
  async statusAll(names) {
    const out = {};
    for (const n of names) {
      const e = children.get(n);
      out[n] = {
        state: e?.state || 'stopped',
        pid: e?.proc?.pid || null,
        memory: null,
        cpu: null,
        restarts: e?.restarts || 0,
        uptime: e?.state === 'running' ? (Date.now() - e.startedAt) / 1000 : null,
      };
    }
    return out;
  },
  async logs(name) {
    return children.get(name)?.logs.text() || '';
  },
  follow(name, onLine) {
    let e = children.get(name);
    if (!e) {
      e = { logs: new LineBuffer(2000), restarts: 0, state: 'stopped' };
      children.set(name, e);
    }
    e.logs.listeners.add(onLine);
    return () => e.logs.listeners.delete(onLine);
  },
};

export const runner = () => (useSystemd() ? systemd : child);
export const runnerKind = () => (useSystemd() ? 'systemd' : 'built-in');

/**
 * On startup: with systemd, regenerate every site's files so older installs get
 * fixed automatically (restarting the ones whose unit changed); with the
 * built-in supervisor, start the sites that should be running.
 */
export async function restoreChildren(sites, commandFor) {
  if (useSystemd()) {
    for (const s of sites) {
      const command = commandFor(s);
      if (!command) continue; // e.g. a Rust site whose Cargo.toml names no program: starting it explains why
      try {
        const changed = await systemd.write(s, command);
        if (changed && s.enabled) {
          console.log(`[sites] Updated service for ${s.name}, restarting`);
          await runOk('systemctl', ['restart', unitName(s.name)]);
        }
      } catch (err) {
        console.error(`[sites] ${s.name}: ${err.message}`);
      }
    }
    return;
  }
  for (const s of sites) if (s.enabled && commandFor(s)) await child.start(s, commandFor(s)).catch(() => {});
}

export async function stopAllChildren() {
  for (const name of children.keys()) await child.stop({ name }).catch(() => {});
}
